# 2. 🤖 GitHub Actions (사용자 요청 반영 + 기능 강화)
# ==============================================================================
def generate_workflow():
    write_file(os.path.join(WORKFLOWS_DIR, "ultimate_ci.yml"), """
name: Ultimate CI/CD (Resource & AI Fix)
on:
  push:
    branches: [ "main" ]
  pull_request:
    branches: [ "main" ]

jobs:
  build-deploy:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read
      checks: write
    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      # 1. Python 환경 (리소스 생성용)
      - name: Set up Python
        uses: actions/setup-python@v4
        with:
          python-version: '3.9'
          cache: 'pip'

      # 2. Java 설정
      - name: Set up JDK 17
        uses: actions/setup-java@v4
        with:
          java-version: '17'
          distribution: 'temurin'
          cache: 'maven'

      # 3. [핵심] 리소스 동적 생성 (JSON 파일 분리 저장)
      - name: 🚀 Run Setup (Externalize Data)
        run: |
          if [ -f setup_resources.py ]; then
            echo "⚡ setup_resources.py 실행: AI 데이터 생성 중..."
            python setup_resources.py
          else
            echo "❌ 설정 스크립트가 없습니다."
            exit 1
          fi

      # 4. 빌드 (생성된 리소스 포함)
      - name: Build with Maven
        working-directory: services/omni-pokemon-web
        run: mvn clean package -DskipTests -B

      # 5. 서버 테스트 (Smart Polling + AI Data 검증)
      - name: 🌐 Server Smoke Test (Smart Mode)
        working-directory: services/omni-pokemon-web
        run: |
          echo "🔥 서버 시작 (JVM 옵션 최적화)..."
          # 한글 인코딩 및 메모리 설정
          nohup java -Xmx512m -Dfile.encoding=UTF-8 -jar target/*.jar > app.log 2>&1 &
          PID=$!
          
          echo "⏳ 부팅 대기 (Smart Polling: Max 60s)..."
          # 기존 sleep 20 -> Smart Loop로 변경
          BOOTED=false
          for i in {1..30}; do
            sleep 2
            HTTP_CODE=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:8086/api/system/health || echo "000")
            if [ "$HTTP_CODE" -eq 200 ]; then
              echo "✅ 서버 가동 확인 (Attempt $i)"
              BOOTED=true
              break
            fi
            echo "   Wait... $i"
          done

          if [ "$BOOTED" = "false" ]; then
             echo "❌ 부팅 타임아웃!"
             cat app.log
             kill $PID
             exit 1
          fi

          echo "🧪 1. Health Check: OK"
          
          echo "🧪 2. 대량 데이터 검색 (Gemini/Claude 확인)"
          # URL 인코딩 테스트
          SEARCH_RES=$(curl -s -G --data-urlencode "keyword=Gemini" http://localhost:8086/api/ai/trends)
          
          echo "Search Result Length: ${#SEARCH_RES}"
          
          # Gemini가 포함되어야 성공
          if [[ "$SEARCH_RES" == *"Gemini"* ]]; then
            echo "✅ 테스트 성공! (AI 데이터 로드 및 인코딩 정상)"
            kill $PID
            exit 0
          else
            echo "❌ 데이터 검증 실패"
            echo "응답: $SEARCH_RES"
            cat app.log
            kill $PID
            exit 1
          fi

      # 6. 아티팩트 업로드
      - name: 📤 Upload Artifact
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: server-logs-and-jar
          path: |
            services/omni-pokemon-web/app.log
            services/omni-pokemon-web/target/*.jar
""")

