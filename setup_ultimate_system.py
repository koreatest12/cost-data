# 4. 🎨 Frontend (PWA + Neon UI)
# ==============================================================================
def generate_frontend():
    # PWA Manifest
    write_file(os.path.join(STATIC_DIR, "manifest.json"), json.dumps({
        "name": "2026 AI Trends",
        "short_name": "AI 2026",
        "start_url": "/",
        "display": "standalone",
        "theme_color": "#0f172a",
        "background_color": "#0f172a",
        "icons": [{"src": "https://cdn-icons-png.flaticon.com/512/2040/2040946.png", "sizes": "512x512", "type": "image/png"}]
    }, indent=2))

    # Service Worker
    write_file(os.path.join(STATIC_DIR, "sw.js"), """
self.addEventListener('install', e => e.waitUntil(caches.open('ai-v8').then(c => c.addAll(['/', '/index.html']))));
self.addEventListener('fetch', e => e.respondWith(caches.match(e.request).then(r => r || fetch(e.request))));
""")

    # HTML
    write_file(os.path.join(STATIC_DIR, "index.html"), """
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>AI 2026 Insight</title>
    <link rel="manifest" href="/manifest.json">
    <script src="https://cdn.tailwindcss.com"></script>
    <script>if('serviceWorker' in navigator) navigator.serviceWorker.register('/sw.js');</script>
</head>
<body class="bg-slate-900 text-white p-6">
    <h1 class="text-3xl font-bold mb-6 text-blue-400">2026 AI Trends (CI Verified)</h1>
    <div id="list" class="space-y-4">Loading...</div>
    <script>
        fetch('/api/ai/trends').then(r => r.json()).then(d => {
            document.getElementById('list').innerHTML = d.rankings.map(r => `
                <div class="bg-slate-800 p-4 rounded-xl border border-slate-700">
                    <span class="text-yellow-400 font-bold">#${r.rank}</span> 
                    <span class="font-bold text-lg ml-2">${r.name}</span>
                    <div class="text-sm text-slate-400">${r.desc}</div>
                </div>
            `).join('');
        });
    </script>
</body>
</html>
""")

